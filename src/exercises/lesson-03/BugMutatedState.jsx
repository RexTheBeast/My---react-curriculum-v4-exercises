/*
  BUG #2 — State Issue

  This component displays a count and updates it when the button is clicked.
  However, the way the count is being changed causes the component to behave
  incorrectly.
*/

import { useState } from 'react';
export default function BugMutatedState() {
  let [count, setCount] = useState(0);

  function handleAdd() {
    setCount((count) => count + 1);
  }

  return (
    <div>
      <p>Bug 2 Count: {count}</p>
      <button onClick={handleAdd}>Add 1</button>
    </div>
  );
}

// Explanation:
// (In this one the problem was count++ was changing the varible in place
//  meaning we are mutating a state directly which is not allowed in react
//  beacsue react does not track mutations. So what we need to do is
//  make it a functional updater so that it take the most recent/newest value)
